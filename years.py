def chapter_label(book: str, ch: int) -> str:
    if book == "Psalms" and ch in PSALMS:
        return PSALMS[ch]
    for b, a, z, lab in CHAPTERS:
        if b == book and a <= ch <= z:
            return lab
    return ""
